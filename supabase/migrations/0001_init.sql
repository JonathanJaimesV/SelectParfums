drop trigger if exists order_items_forbid_trg on public.order_items;
create trigger order_items_forbid_trg before update or delete on public.order_items for each row execute function public.forbid_change();
drop trigger if exists order_events_forbid_trg on public.order_events;
create trigger order_events_forbid_trg before update or delete on public.order_events for each row execute function public.forbid_change();

-- ───────────────────────────── 4. Reglas de estado de pedidos ─────────────────────────────
-- TRANSICIONES (la UI y las pruebas leen esta misma tabla; mantener sincronizado con src/backend/orderStatus.js):
--   iniciado               → pendiente_confirmacion | confirmado | cancelado
--   pendiente_confirmacion → confirmado | cancelado
--   confirmado             → pendiente_pago | pagado | cancelado
--   pendiente_pago         → pagado | cancelado
--   pagado                 → en_preparacion | cancelado
--   en_preparacion         → enviado | cancelado
--   enviado                → entregado
--   entregado, cancelado   → (finales)
create or replace function public.order_transition_allowed(p_from text, p_to text)
returns boolean language sql immutable as $$
  select case p_from
    when 'iniciado'               then p_to in ('pendiente_confirmacion','confirmado','cancelado')
    when 'pendiente_confirmacion' then p_to in ('confirmado','cancelado')
    when 'confirmado'             then p_to in ('pendiente_pago','pagado','cancelado')
    when 'pendiente_pago'         then p_to in ('pagado','cancelado')
    when 'pagado'                 then p_to in ('en_preparacion','cancelado')
    when 'en_preparacion'         then p_to in ('enviado','cancelado')
    when 'enviado'                then p_to in ('entregado')
    else false
  end;
$$;

-- ───────────────────────────── 5. Funciones (lógica de negocio en el servidor) ─────────────────────────────
create or replace function public.order_to_json(p_order_id uuid) returns jsonb
language sql security definer stable set search_path = public as $$
  select jsonb_build_object(
    'order_id', o.id, 'code', o.code, 'status', o.status, 'total_cop', o.total_cop, 'created_at', o.created_at,
    'items', coalesce((select jsonb_agg(jsonb_build_object(
        'line_no', i.line_no, 'product_id', i.product_id, 'brand', i.product_brand, 'name', i.product_name, 'slug', i.product_slug,
        'presentation_kind', i.presentation_kind, 'presentation_label', i.presentation_label, 'availability', i.availability_at_order,
        'quantity', i.quantity, 'unit_price_cop', i.unit_price_cop, 'subtotal_cop', i.subtotal_cop) order by i.line_no)
      from public.order_items i where i.order_id = o.id), '[]'::jsonb))
  from public.orders o where o.id = p_order_id;
$$;
revoke all on function public.order_to_json(uuid) from public;

-- create_order: la ÚNICA vía para que un visitante cree un pedido. Revalida todo en el servidor.
-- p_items = [{"product_id":3,"kind":"5","quantity":2}, ...]
-- Orden: 1) validar y calcular TODO en memoria; 2) solo si todo es válido, insertar cabecera y líneas.
-- Errores: 22023 (datos inválidos), P0001 'ITEM_UNAVAILABLE:<product_id>:<kind>:<motivo>'.
create or replace function public.create_order(p_client_request_id uuid, p_items jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_existing uuid;
  v_order_id uuid := gen_random_uuid();
  v_code text;
  v_alphabet constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  v_try integer := 0;
  v_lines jsonb := '[]'::jsonb;   -- líneas ya validadas, listas para insertar
  v_total bigint := 0;
  v_count integer := 0;
  l record;
  prod public.products%rowtype;
  pres public.product_presentations%rowtype;
begin
  if p_client_request_id is null then raise exception 'client_request_id requerido' using errcode = '22023'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 40 then
    raise exception 'items inválidos' using errcode = '22023';
  end if;

  -- Idempotencia: el mismo client_request_id devuelve el pedido ya creado (doble clic, recarga, reintento).
  select id into v_existing from public.orders where client_request_id = p_client_request_id;
  if found then return public.order_to_json(v_existing); end if;

  -- Formato de cada línea ANTES de convertir tipos (evita errores técnicos de conversión con "abc", 1.5 o -3).
  if exists (select 1 from jsonb_array_elements(p_items) e
             where jsonb_typeof(e) <> 'object' or coalesce(e->>'product_id', '') !~ '^[0-9]{1,9}$'
                or coalesce(e->>'quantity', '') !~ '^[0-9]{1,4}$' or coalesce(e->>'kind', '') not in ('5','10','full')) then
    raise exception 'línea inválida' using errcode = '22023';
  end if;

  -- 1) Agrupar líneas repetidas (mismo producto + presentación) y validar cada una contra el catálogo ACTUAL.
  for l in
    select (e->>'product_id')::integer as product_id, e->>'kind' as kind, sum((e->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) e
    group by 1, 2
    order by 1, 2
  loop
    if l.product_id is null or l.kind not in ('5','10','full') or l.quantity is null or l.quantity < 1 or l.quantity > 20 then
      raise exception 'línea inválida' using errcode = '22023';
    end if;
    select * into prod from public.products where id = l.product_id;
    if not found or prod.status <> 'published' then
      raise exception 'ITEM_UNAVAILABLE:%:%:no_existe', l.product_id, l.kind using errcode = 'P0001';
    end if;
    if prod.availability = 'Agotado' then
      raise exception 'ITEM_UNAVAILABLE:%:%:agotado', l.product_id, l.kind using errcode = 'P0001';
    end if;
    select * into pres from public.product_presentations where product_id = l.product_id and kind = l.kind;
    if not found or not pres.enabled then
      raise exception 'ITEM_UNAVAILABLE:%:%:presentacion_inactiva', l.product_id, l.kind using errcode = 'P0001';
    end if;
    if pres.price_cop is null then
      raise exception 'ITEM_UNAVAILABLE:%:%:sin_precio', l.product_id, l.kind using errcode = 'P0001';
    end if;
    v_count := v_count + 1;
    v_total := v_total + pres.price_cop::bigint * l.quantity;
    v_lines := v_lines || jsonb_build_array(jsonb_build_object(
      'line_no', v_count, 'product_id', prod.id, 'brand', prod.brand, 'name', prod.name, 'slug', prod.slug,
      'kind', l.kind,
      'label', case l.kind when '5' then 'Decant de 5 ml' when '10' then 'Decant de 10 ml' else 'Frasco completo (' || prod.bottle_size || ')' end,
      'availability', prod.availability, 'quantity', l.quantity, 'unit', pres.price_cop));
  end loop;

  -- 2) Código legible y único: SP-AAMMDD-XXXX (sin caracteres ambiguos).
  loop
    v_try := v_try + 1;
    v_code := 'SP-' || to_char(now() at time zone 'America/Bogota', 'YYMMDD') || '-' ||
      (select string_agg(substr(v_alphabet, 1 + floor(random() * length(v_alphabet))::int, 1), '') from generate_series(1, 4));
    exit when not exists (select 1 from public.orders where code = v_code);
    if v_try > 20 then raise exception 'no se pudo generar el código' using errcode = '55000'; end if;
  end loop;

  -- 3) Insertar TODO (cabecera con total real + líneas con copia inmutable). Si algo falla, no queda nada a medias.
  begin
    insert into public.orders(id, code, client_request_id, total_cop, item_count)
      values (v_order_id, v_code, p_client_request_id, v_total, v_count);
  exception when unique_violation then
    -- Otra transacción con el mismo client_request_id insertó primero. Como aún puede no estar confirmada,
    -- reintentamos la lectura hasta encontrarla (el unique garantiza que existe, o que se rechaza).
    for v_try in 1..20 loop
      select id into v_existing from public.orders where client_request_id = p_client_request_id;
      if found then return public.order_to_json(v_existing); end if;
      perform pg_sleep(0.05);
    end loop;
    raise exception 'no se pudo confirmar el pedido; reintenta' using errcode = '55P03';
  end;

  insert into public.order_items(order_id, line_no, product_id, product_brand, product_name, product_slug,
      presentation_kind, presentation_label, availability_at_order, quantity, unit_price_cop, subtotal_cop)
  select v_order_id, (x->>'line_no')::integer, (x->>'product_id')::integer, x->>'brand', x->>'name', x->>'slug',
         x->>'kind', x->>'label', x->>'availability', (x->>'quantity')::integer, (x->>'unit')::integer,
         (x->>'unit')::bigint * (x->>'quantity')::integer
  from jsonb_array_elements(v_lines) x;

  insert into public.order_events(order_id, from_status, to_status, note) values (v_order_id, null, 'iniciado', 'Solicitud registrada desde la tienda');
  return public.order_to_json(v_order_id);
end $$;
revoke all on function public.create_order(uuid, jsonb) from public;
grant execute on function public.create_order(uuid, jsonb) to anon, authenticated;

-- Cambio de estado: solo administradores y solo transiciones permitidas. Registra el historial.
create or replace function public.admin_set_order_status(p_order_id uuid, p_to text, p_note text default '')
returns jsonb language plpgsql security definer set search_path = public as $$
declare cur text;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode = '42501'; end if;
  select status into cur from public.orders where id = p_order_id for update;
  if not found then raise exception 'ORDER_NOT_FOUND' using errcode = 'P0002'; end if;
  if not public.order_transition_allowed(cur, p_to) then
    raise exception 'TRANSITION_NOT_ALLOWED:%:%', cur, p_to using errcode = 'P0001';
  end if;
  update public.orders set status = p_to, updated_at = now() where id = p_order_id;
  insert into public.order_events(order_id, from_status, to_status, note, actor) values (p_order_id, cur, p_to, coalesce(p_note, ''), auth.uid());
  return public.order_to_json(p_order_id);
end $$;
revoke all on function public.admin_set_order_status(uuid, text, text) from public;
grant execute on function public.admin_set_order_status(uuid, text, text) to authenticated;

create or replace function public.admin_set_order_notes(p_order_id uuid, p_notes text)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode = '42501'; end if;
  update public.orders set admin_notes = left(coalesce(p_notes, ''), 4000), updated_at = now() where id = p_order_id;
  if not found then raise exception 'ORDER_NOT_FOUND' using errcode = 'P0002'; end if;
  return public.order_to_json(p_order_id);
end $$;
revoke all on function public.admin_set_order_notes(uuid, text) from public;
grant execute on function public.admin_set_order_notes(uuid, text) to authenticated;

-- Guardado ATÓMICO de un perfume + sus 3 presentaciones (o todo o nada).
-- p = {"id":3|null,"slug":..,"brand":..,"name":..,"description":..,"bottle_size":..,"category":..,"genders":[..],"notes":{..},
--      "images":[..],"status":..,"availability":..,"featured":bool,"presentations":{"5":{"enabled":true,"price_cop":23000},...}}
create or replace function public.admin_save_product(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_id integer;
  k text;
  pr jsonb;
  v_price integer;
  v_status text := coalesce(p->>'status', 'published');
  v_avail  text := coalesce(p->>'availability', 'Disponible');
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode = '42501'; end if;
  if jsonb_typeof(p) <> 'object' then raise exception 'Datos del perfume inválidos' using errcode = '22023'; end if;
  -- Validaciones con mensajes claros (antes de tocar nada)
  if nullif(btrim(coalesce(p->>'slug','')), '') is null or (p->>'slug') !~ '^[a-z0-9]+(-[a-z0-9]+)*$' then
    raise exception 'El slug debe tener solo minúsculas, números y guiones' using errcode = '22023'; end if;
  if nullif(btrim(coalesce(p->>'brand','')), '') is null then raise exception 'La marca es obligatoria' using errcode = '22023'; end if;
  if nullif(btrim(coalesce(p->>'name','')), '') is null then raise exception 'El nombre es obligatorio' using errcode = '22023'; end if;
  if (p->>'category') not in ('Hombre','Mujer','Unisex') then raise exception 'Categoría no válida' using errcode = '22023'; end if;
  if v_status not in ('published','hidden','archived') then raise exception 'Estado no válido' using errcode = '22023'; end if;
  if v_avail not in ('Disponible','Preventa','Agotado') then raise exception 'Disponibilidad no válida' using errcode = '22023'; end if;
  if coalesce(p->>'bottle_size','100 ml') !~ '^[0-9]+ ?ml$' then raise exception 'Tamaño de frasco no válido' using errcode = '22023'; end if;
  if p->'images' is not null and (jsonb_typeof(p->'images') <> 'array' or jsonb_array_length(p->'images') > 3) then
    raise exception 'Máximo 3 fotografías por perfume' using errcode = '22023'; end if;
  v_id := nullif(p->>'id', '')::integer;
  if v_id is null then
    if exists (select 1 from public.products where slug = p->>'slug') or exists (select 1 from public.product_slugs where slug = p->>'slug') then
      raise exception 'Ese slug ya existe (en un perfume actual o anterior)' using errcode = '23505'; end if;
    insert into public.products(slug, brand, name, description, bottle_size, category, genders, notes, images, status, availability, featured)
    values (p->>'slug', p->>'brand', p->>'name', coalesce(p->>'description',''), coalesce(p->>'bottle_size','100 ml'), p->>'category',
            coalesce(array(select jsonb_array_elements_text(coalesce(p->'genders','[]'::jsonb))), '{}'),
            case when jsonb_typeof(p->'notes') = 'object' then p->'notes' else '{}'::jsonb end,
            case when jsonb_typeof(p->'images') = 'array' then p->'images' else '[]'::jsonb end,
            coalesce(p->>'status','published'), coalesce(p->>'availability','Disponible'), coalesce((p->>'featured')::boolean, false))
    returning id into v_id;
  else
    -- Actualización PARCIAL: los campos omitidos conservan su valor actual (no se borran fotos ni notas por omisión).
    if not exists (select 1 from public.products where id = v_id) then
      raise exception 'PRODUCT_NOT_FOUND' using errcode = 'P0002'; end if;
    if exists (select 1 from public.products where slug = p->>'slug' and id <> v_id) then
      raise exception 'Ese slug ya pertenece a otro perfume' using errcode = '23505'; end if;
    update public.products set
      slug         = coalesce(p->>'slug', slug),
      brand        = coalesce(p->>'brand', brand),
      name         = coalesce(p->>'name', name),
      description  = coalesce(p->>'description', description),
      bottle_size  = coalesce(p->>'bottle_size', bottle_size),
      category     = coalesce(p->>'category', category),
      genders      = case when p->'genders' is not null then coalesce(array(select jsonb_array_elements_text(p->'genders')), '{}') else genders end,
      notes        = case when jsonb_typeof(p->'notes') = 'object' then p->'notes' else notes end,
      images       = case when jsonb_typeof(p->'images') = 'array' then p->'images' else images end,
      status       = coalesce(p->>'status', status),
      availability = coalesce(p->>'availability', availability),
      featured     = coalesce((p->>'featured')::boolean, featured)
    where id = v_id;
  end if;
  foreach k in array array['5','10','full'] loop
    pr := p->'presentations'->k;
    if pr is null then continue; end if;
    if pr->>'price_cop' is not null and pr->>'price_cop' !~ '^[0-9]+$' then
      raise exception 'El precio de % debe ser un número entero de pesos colombianos', k using errcode = '22023'; end if;
    v_price := nullif(pr->>'price_cop', '')::integer;
    if v_price is not null and v_price <= 0 then
      raise exception 'El precio de % debe ser mayor que cero', k using errcode = '22023'; end if;
    insert into public.product_presentations(product_id, kind, enabled, price_cop)
    values (v_id, k, coalesce((pr->>'enabled')::boolean, true), v_price)
    on conflict (product_id, kind) do update set enabled = excluded.enabled, price_cop = excluded.price_cop;
  end loop;
  return jsonb_build_object('id', v_id);
end $$;
revoke all on function public.admin_save_product(jsonb) from public;
grant execute on function public.admin_save_product(jsonb) to authenticated;

-- Inventario: la cantidad solo se guarda si el administrador declara que la verificó.
create or replace function public.admin_set_inventory(p_product_id integer, p_kind text, p_state text, p_quantity integer, p_verified boolean, p_notes text)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode = '42501'; end if;
  if p_quantity is not null and not coalesce(p_verified, false) then
    raise exception 'La cantidad solo se registra si fue verificada' using errcode = '22023';
  end if;
  insert into public.inventory(product_id, kind, state, quantity, quantity_verified_at, notes, updated_by, updated_at)
  values (p_product_id, p_kind, p_state, p_quantity, case when p_quantity is not null then now() end, left(coalesce(p_notes,''), 2000), auth.uid(), now())
  on conflict (product_id, kind) do update set state = excluded.state, quantity = excluded.quantity,
    quantity_verified_at = excluded.quantity_verified_at, notes = excluded.notes, updated_by = excluded.updated_by, updated_at = now();
  return jsonb_build_object('product_id', p_product_id, 'kind', p_kind);
end $$;
revoke all on function public.admin_set_inventory(integer, text, text, integer, boolean, text) from public;
grant execute on function public.admin_set_inventory(integer, text, text, integer, boolean, text) to authenticated;

