-- ───────────────────────────── 1. Administradores ─────────────────────────────
-- Lista de usuarios autorizados. Nadie puede insertarse desde la web: solo se agrega con SQL
-- (rol postgres del SQL Editor). Ver docs/ADMIN-SETUP.md → «Crear el primer administrador».
create table if not exists public.admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  role       text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now()
);
alter table public.admins enable row level security;
drop policy if exists admins_read_self on public.admins;
create policy admins_read_self on public.admins for select to authenticated using (user_id = auth.uid());

create or replace function public.is_admin()
returns boolean language sql security definer stable set search_path = public as $$
  select exists (select 1 from public.admins a where a.user_id = auth.uid());
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ───────────────────────────── 2. Catálogo ─────────────────────────────
-- id estable (la semilla conserva los ids actuales, que usan el carrito y los pedidos).
create table if not exists public.products (
  id          integer generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  brand       text not null check (length(btrim(brand)) > 0),
  name        text not null check (length(btrim(name)) > 0),
  description text not null default '',
  bottle_size text not null default '100 ml' check (bottle_size ~ '^[0-9]+ ?ml$'),
  category    text not null check (category in ('Hombre','Mujer','Unisex')),
  genders     text[] not null default '{}',
  notes       jsonb not null default '{}'::jsonb,
  images      jsonb not null default '[]'::jsonb check (jsonb_typeof(images) = 'array' and jsonb_array_length(images) <= 3),
  status      text not null default 'published' check (status in ('published','hidden','archived')),
  availability text not null default 'Disponible' check (availability in ('Disponible','Preventa','Agotado')),
  featured    boolean not null default false,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Presentaciones: 5 = decant 5 ml, 10 = decant 10 ml, full = frasco completo.
-- price_cop NULL = "Consultar" (no se puede agregar al carrito). Nunca se calcula un precio a partir de otro.
create table if not exists public.product_presentations (
  product_id integer not null references public.products(id) on update cascade on delete restrict,
  kind       text not null check (kind in ('5','10','full')),
  enabled    boolean not null default true,
  price_cop  integer check (price_cop is null or price_cop > 0),
  primary key (product_id, kind)
);

-- Todos los slugs que ha tenido cada perfume: las URL antiguas siguen funcionando (redirigen al slug actual).
create table if not exists public.product_slugs (
  slug       text primary key,
  product_id integer not null references public.products(id) on update cascade on delete cascade,
  created_at timestamptz not null default now()
);

-- Inventario (v1: estados explícitos; cantidad solo si fue verificada). NO bloquea ventas.
create table if not exists public.inventory (
  product_id integer not null references public.products(id) on update cascade on delete restrict,
  kind       text not null check (kind in ('5','10','full')),
  state      text not null default 'sin_configurar' check (state in ('sin_configurar','disponible','agotado','preventa')),
  quantity   integer check (quantity is null or quantity >= 0),
  quantity_verified_at timestamptz,
  notes      text not null default '',
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id),
  primary key (product_id, kind),
  constraint inventory_qty_needs_verification check (quantity is null or quantity_verified_at is not null)
);

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products for each row execute function public.touch_updated_at();

-- El id de un producto nunca cambia; cada slug (actual o anterior) queda registrado.
create or replace function public.products_guard() returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' and new.id <> old.id then raise exception 'El id de un producto es inmutable' using errcode = '23514'; end if;
  return new;
end $$;
drop trigger if exists products_guard_trg on public.products;
create trigger products_guard_trg before update on public.products for each row execute function public.products_guard();

create or replace function public.products_track_slug() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' or new.slug <> old.slug then
    insert into public.product_slugs(slug, product_id) values (new.slug, new.id) on conflict (slug) do nothing;
    if not exists (select 1 from public.product_slugs s where s.slug = new.slug and s.product_id = new.id) then
      raise exception 'El slug "%" ya pertenece a otro perfume', new.slug using errcode = '23505';
    end if;
  end if;
  return null;
end $$;
drop trigger if exists products_track_slug_trg on public.products;
create trigger products_track_slug_trg after insert or update of slug on public.products for each row execute function public.products_track_slug();

-- ───────────────────────────── 3. Pedidos ─────────────────────────────
-- Un pedido es una SOLICITUD registrada antes de abrir WhatsApp. Abrir WhatsApp ≠ pedido confirmado.
create table if not exists public.orders (
  id                uuid primary key default gen_random_uuid(),
  code              text not null unique,
  client_request_id uuid not null unique,                       -- idempotencia: mismo id = mismo pedido
  status            text not null default 'iniciado' check (status in
    ('iniciado','pendiente_confirmacion','confirmado','pendiente_pago','pagado','en_preparacion','enviado','entregado','cancelado')),
  total_cop         bigint not null check (total_cop > 0),
  item_count        integer not null check (item_count > 0),
  admin_notes       text not null default '',
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- Copia INMUTABLE de lo vigente al crear el pedido: cambiar nombre, imagen o precio después no lo altera.
create table if not exists public.order_items (
  order_id             uuid not null references public.orders(id) on delete cascade,
  line_no              integer not null,
  product_id           integer not null references public.products(id) on delete restrict,
  product_brand        text not null,
  product_name         text not null,
  product_slug         text not null,
  presentation_kind    text not null check (presentation_kind in ('5','10','full')),
  presentation_label   text not null,
  availability_at_order text not null,
  quantity             integer not null check (quantity between 1 and 20),
  unit_price_cop       integer not null check (unit_price_cop > 0),
  subtotal_cop         bigint not null,
  primary key (order_id, line_no),
  constraint order_items_subtotal_ok check (subtotal_cop = unit_price_cop::bigint * quantity)
);

create table if not exists public.order_events (
  id         bigint generated always as identity primary key,
  order_id   uuid not null references public.orders(id) on delete cascade,
  from_status text,
  to_status  text not null,
  note       text not null default '',
  actor      uuid,
  created_at timestamptz not null default now()
);
create index if not exists orders_status_created_idx on public.orders(status, created_at desc);
create index if not exists order_events_order_idx on public.order_events(order_id, id);

-- Defensa en profundidad: lo que no debe cambiar nunca, no cambia (ni siquiera con permisos de administrador).
create or replace function public.orders_immutable() returns trigger language plpgsql as $$
begin
  if new.id <> old.id or new.code <> old.code or new.client_request_id <> old.client_request_id
     or new.total_cop <> old.total_cop or new.item_count <> old.item_count or new.created_at <> old.created_at then
    raise exception 'Los datos comerciales de un pedido son inmutables' using errcode = '23514';
  end if;
  return new;
end $$;
drop trigger if exists orders_immutable_trg on public.orders;
create trigger orders_immutable_trg before update on public.orders for each row execute function public.orders_immutable();

create or replace function public.forbid_change() returns trigger language plpgsql as $$
begin raise exception 'Registro histórico: no se puede modificar ni borrar' using errcode = '23514'; end $$;
-- Sin excepciones: ni triggers ni administradores pueden modificar el histórico.
